/* Basic project smoke tests for the live-map WayFind interface. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
for(const f of ['index.html','style.css','script.js','manifest.webmanifest','sw.js','icon.svg','server.js'])assert.ok(fs.existsSync(path.join(root,f)),'Missing required file: '+f);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'script.js'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
assert.match(html,/maplibre-gl\.css/,'MapLibre stylesheet must be present');
assert.match(html,/id="roadMap"/,'Interactive map container must exist');
assert.match(html,/src="\.\/script\.js"/,'Main script must load');
assert.match(html,/href="\.\/style\.css"/,'Main stylesheet must load');
for(const id of ['routeForm','from','to','directionsPanel','stepsList','startNavBtn','stopNavBtn','roadPhoto','readPhotoBtn','photoText','routeSummary','tiltBtn'])assert.ok(html.includes('id="'+id+'"'),'Missing control: '+id);
assert.doesNotMatch(html+js,/google\.com\/maps|maps\.googleapis\.com/i,'Google Maps UI and handoffs should not be present');
assert.match(js,/new maplibregl\.Map/,'Main interface must initialize an interactive map');
assert.match(js,/basemaps\.cartocdn\.com/,'Map must use a non-Google basemap');
assert.match(js,/router\.project-osrm\.org/,'Driving route service must be wired');
assert.match(js,/wayfind-route-line/,'Route geometry must draw over the basemap');
assert.match(js,/watchPosition/,'Live GPS tracking must be wired');
assert.match(js,/tesseract\.js/,'Photo OCR must be wired');
assert.match(css,/\.road-map/,'Map container must be styled');
assert.match(css,/\.input-wrap \.field:focus-visible/,'Oversized input focus outline must be corrected');
assert.match(css,/@media\(max-width:760px\)/,'Responsive layout must exist');
assert.match(fs.readFileSync(path.join(root,'sw.js'),'utf8'),/wayfind-navigation-v4/,'Cache version must be updated');
console.log('WayFind live-map smoke checks passed.');
